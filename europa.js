let currentQuestion = 0;
let score = 0;
let answered = false;


function loadQuestion() {

    answered = false;

    const q = questions[currentQuestion];

    document.getElementById("quiz-progress").textContent =
        `QUESTION ${currentQuestion + 1} / ${questions.length}`;

    document.getElementById("quiz-question").textContent = q.question;

    document.getElementById("quiz-feedback").textContent = "";

    document.getElementById("next-question").classList.add("hidden");

    const answersContainer = document.getElementById("quiz-answers");

    answersContainer.innerHTML = "";

    q.answers.forEach((answer, index) => {

        const button = document.createElement("button");

        button.className = "answer-button";
        button.textContent = answer;

        button.addEventListener("click", () => checkAnswer(index));

        answersContainer.appendChild(button);

    });

}


function checkAnswer(selected) {

    if (answered) return;

    answered = true;

    const q = questions[currentQuestion];

    const buttons = document.querySelectorAll(".answer-button");

    buttons.forEach((button, index) => {

        button.disabled = true;

        if (index === q.correct) {
            button.classList.add("correct");
        }

        if (index === selected && selected !== q.correct) {
            button.classList.add("wrong");
        }

    });

    if (selected === q.correct) {
        score++;

        document.getElementById("quiz-feedback").textContent =
            "✓ Richtig! " + q.explanation;

    } else {

        document.getElementById("quiz-feedback").textContent =
            "✕ Leider falsch. " + q.explanation;

    }

    const nextButton = document.getElementById("next-question");

    nextButton.classList.remove("hidden");

    nextButton.textContent =
        currentQuestion === questions.length - 1
        ? "SHOW RESULTS →"
        : "NEXT QUESTION →";

}


function nextQuestion() {

    currentQuestion++;

    if (currentQuestion < questions.length) {

        loadQuestion();

    } else {

        showResults();

    }

}


function showResults() {

    document.getElementById("quiz-progress").textContent =
        "QUIZ COMPLETED";

    document.getElementById("quiz-question").textContent =
        `YOU GOT ${score} / ${questions.length} POINTS!`;

    document.getElementById("quiz-answers").innerHTML = "";

    document.getElementById("quiz-feedback").textContent =
        score === questions.length
        ? "Perfekt! Du kennst dich mit der europäischen Kulturpolitik aus."
        : "Geschafft! Entdecke die Themen noch einmal und teste dein Wissen erneut.";

    const nextButton = document.getElementById("next-question");

    nextButton.textContent = "PLAY AGAIN ↻";

    nextButton.classList.remove("hidden");

    nextButton.onclick = restartQuiz;

}


function restartQuiz() {

    currentQuestion = 0;
    score = 0;

    const nextButton = document.getElementById("next-question");

    nextButton.onclick = nextQuestion;

    loadQuestion();

}


