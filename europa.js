// THEMEN ÖFFNEN

function openTopic(topicName) {

    const topic = topics[topicName];

    if (!topic) return;

    const content = document.getElementById("topic-content");

    let cardsHTML = "";

    topic.cards.forEach(card => {

        cardsHTML += `
            <article class="info-card">
                <h3>${card.title}</h3>
                <p>${card.text}</p>
                ${
                    card.placeholder
                    ? `<p class="placeholder">✎ ${card.placeholder}</p>`
                    : ""
                }
            </article>
        `;
    });

    content.innerHTML = `
        <p class="eyebrow">${topic.subtitle}</p>
        <h2 class="topic-title">${topic.title}</h2>
        <p class="topic-description">${topic.description}</p>

        <div class="info-grid">
            ${cardsHTML}
        </div>
    `;

    document.getElementById("topic-area").classList.remove("hidden");

    document.getElementById("topic-area").scrollIntoView({
        behavior: "smooth"
    });
}


